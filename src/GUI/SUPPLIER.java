    public String generateIdBarang() {
        String newId = "PT001";

        try {
            Connection conn = KONEKSI.getConnection();
            String query = "SELECT id_supplier FROM supplier ORDER BY id_supplier DESC LIMIT 1";
            PreparedStatement ps = conn.prepareStatement(query);
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                String lastId = rs.getString("id_supplier"); // ex: "BRG004"
                int number = Integer.parseInt(lastId.substring(3)); // ambil angka: 4
                number++; // jadi 5
                newId = String.format("PT%03d", number); // jadi "BRG005"
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    
        return newId;
    }
    
