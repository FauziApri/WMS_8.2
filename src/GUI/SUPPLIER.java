    private void btn_ADDActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_ADDActionPerformed
        int baris = tabel_barang.getSelectedRow();
        
        String id = generateIdBarang();
        String nama = nama_supplier.getText();
        String barang = tampil_namabrg.getText();
        String alamat = alamat_supplier.getText();

        if (!nama.isEmpty()) {
            DefaultTableModel model = (DefaultTableModel) tabel_supplier.getModel();
            DefaultTableModel model_brg = (DefaultTableModel) tabel_barang.getModel();
            boolean add = supplier.input(id, nama, barang, alamat);
            
            if (add){
                JOptionPane.showMessageDialog(this, "Data Berhasil Ditambahkan ke Tabel!");
                model.addRow(new Object[]{id, nama, barang, alamat});
                model_brg.removeRow(baris);
            } else {
                JOptionPane.showMessageDialog(this, "Gagal Menyimpan ke Database");
            }
            
            resetData();
        } else {
            JOptionPane.showMessageDialog(this, "Isi Nama Barang terlebih dahulu!");
        }
    }//GEN-LAST:event_btn_ADDActionPerformed

